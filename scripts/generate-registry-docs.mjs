import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

import prettierConfig from "../.prettierrc.mjs";
import { builtinPaymentChannels } from "../dist/esm/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedDirectory = path.join(root, "docs", "generated");
const check = process.argv.includes("--check");
const json = await format(JSON.stringify(builtinPaymentChannels), {
  ...prettierConfig,
  parser: "json",
});
const rows = builtinPaymentChannels.map(
  (schema) =>
    `| \`${schema.id}\` | ${schema.display.label} | \`${schema.network.country}\` | \`${schema.network.currency}\` | \`${schema.display.group}\` | \`${schema.support.automation}\` | ${schema.version} |`,
);
const markdown = await format(
  `# Built-in payment channels

> Generated by \`npm run docs:generate\` from \`builtinPaymentChannels\`. Do not edit this file directly.

The runtime registry is authoritative. This inventory is provided for human inspection and records the registry order.

| ID | Label | Country | Currency | Group | Automation | Version |
| --- | --- | --- | --- | --- | --- | ---: |
${rows.join("\n")}
`,
  { ...prettierConfig, parser: "markdown" },
);

const outputs = [
  [path.join(generatedDirectory, "registry.json"), json],
  [path.join(generatedDirectory, "built-in-channels.md"), markdown],
];

if (check) {
  const stale = [];
  for (const [filename, expected] of outputs) {
    let actual;
    try {
      actual = await readFile(filename, "utf8");
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    if (actual !== expected) stale.push(path.relative(root, filename));
  }
  if (stale.length > 0) {
    console.error(`Generated registry documentation is stale: ${stale.join(", ")}`);
    console.error("Run npm run docs:generate and commit the result.");
    process.exitCode = 1;
  } else {
    console.log("Generated registry documentation is current.");
  }
} else {
  await mkdir(generatedDirectory, { recursive: true });
  for (const [filename, contents] of outputs) await writeFile(filename, contents);
  console.log("Generated docs/generated/registry.json and docs/generated/built-in-channels.md.");
}
